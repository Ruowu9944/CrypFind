def binary_auc_torch(y_true: Tensor, y_score: Tensor) -> float:
    """
    Compute ROC-AUC in pure torch (CPU) to avoid external deps.
    Returns NaN when only one class is present.
    """
    y_true = y_true.detach().float().cpu().view(-1)
    y_score = y_score.detach().float().cpu().view(-1)

    pos = (y_true == 1).sum().item()
    neg = (y_true == 0).sum().item()
    if pos == 0 or neg == 0:
        return float("nan")

    order = torch.argsort(y_score, descending=False)
    ranks = torch.empty_like(order, dtype=torch.float32)
    ranks[order] = torch.arange(1, len(y_score) + 1, dtype=torch.float32)
    rank_sum_pos = ranks[y_true == 1].sum().item()
    auc = (rank_sum_pos - pos * (pos + 1) / 2.0) / (pos * neg)
    return float(auc)


def edge_loss_with_empty_support(
    edge_logits: Tensor,
    edge_label: Tensor,
    pos_weight: Tensor,
) -> Tuple[Tensor, int]:
    if edge_label.numel() == 0:
        return edge_logits.new_zeros(()), 0
    loss = F.binary_cross_entropy_with_logits(
        edge_logits,
        edge_label.float(),
        pos_weight=pos_weight,
    )
    return loss, int(edge_label.numel())


def sampled_apo_holo_contrastive_loss(
    model: EdgeGCLModel,
    z_apo: Tensor,
    z_holo: Tensor,
    apo_pos: Tensor,
    holo_pos: Tensor,
    batch: Tensor,
    args: argparse.Namespace,
) -> Tuple[Tensor, Dict[str, float]]:
    """Symmetric residue-level apo/holo InfoNCE with per-protein sampling.

    Positive pairs are matched residues from the same apo-holo graph. By
    default, off-diagonal residues from the same protein are masked out. The
    v2 negative option also admits same-protein residues that are far in both
    sequence index and apo CA space, which discourages broad false positives.
    """
    sample_indices: List[Tensor] = []
    sample_graph_ids: List[Tensor] = []
    displacement = (apo_pos - holo_pos).norm(dim=-1)
    positive_cutoff = float(args.contrastive_max_ca_displacement)
    stable_cutoff = float(getattr(args, "contrastive_stable_ca_displacement", 0.0))
    if stable_cutoff > 0:
        positive_cutoff = min(positive_cutoff, stable_cutoff)

    for graph_id in torch.unique(batch):
        graph_mask = batch == graph_id
        eligible_mask = graph_mask & (displacement <= positive_cutoff)

        local_change_cutoff = float(getattr(args, "contrastive_local_change_cutoff", 0.0))
        if local_change_cutoff > 0 and bool(eligible_mask.any()):
            graph_idx = torch.nonzero(graph_mask, as_tuple=False).view(-1)
            apo = apo_pos[graph_idx]
            holo = holo_pos[graph_idx]
            if graph_idx.numel() > 1:
                d_apo = torch.cdist(apo, apo)
                d_holo = torch.cdist(holo, holo)
                not_self = ~torch.eye(graph_idx.numel(), device=apo_pos.device, dtype=torch.bool)
                local_neighbors = (d_apo < float(args.contrastive_local_neighbor_cutoff)) & not_self
                local_neighbor_count = local_neighbors.sum(dim=1)
                local_change = ((d_holo - d_apo).abs() * local_neighbors.to(apo_pos.dtype)).sum(dim=1)
                local_change = local_change / local_neighbor_count.clamp(min=1).to(apo_pos.dtype)
                has_enough_neighbors = local_neighbor_count >= int(args.contrastive_local_min_neighbors)
                local_mask = torch.zeros_like(graph_mask)
                local_mask[graph_idx] = (local_change <= local_change_cutoff) & has_enough_neighbors
                eligible_mask = eligible_mask & local_mask

        eligible = torch.nonzero(eligible_mask, as_tuple=False).view(-1)
        if eligible.numel() == 0:
            continue
        max_samples = int(args.contrastive_samples_per_graph)
        if max_samples > 0 and eligible.numel() > max_samples:
            perm = torch.randperm(eligible.numel(), device=eligible.device)[:max_samples]
            eligible = eligible[perm]
        sample_indices.append(eligible)
        sample_graph_ids.append(torch.full_like(eligible, int(graph_id.item())))

    if len(sample_indices) < 2:
        zero = (z_apo.sum() + z_holo.sum()) * 0.0
        return zero, {
            "contrastive_count": 0.0,
            "contrastive_acc": float("nan"),
            "contrastive_pos_sim": float("nan"),
            "contrastive_neg_per_anchor": 0.0,
        }

    idx = torch.cat(sample_indices, dim=0)
    graph_ids = torch.cat(sample_graph_ids, dim=0)
    if idx.numel() < 2 or torch.unique(graph_ids).numel() < 2:
        zero = (z_apo.sum() + z_holo.sum()) * 0.0
        return zero, {
            "contrastive_count": 0.0,
            "contrastive_acc": float("nan"),
            "contrastive_pos_sim": float("nan"),
            "contrastive_neg_per_anchor": 0.0,
        }

    q = F.normalize(model.contrastive_head.projector(z_apo[idx]), dim=-1)
    k = F.normalize(model.contrastive_head.projector(z_holo[idx]), dim=-1)
    logits = q @ k.t() / float(model.contrastive_head.temperature)
    labels = torch.arange(logits.size(0), device=logits.device)

    if args.contrastive_negatives in {"other_protein", "other_protein_far_same_protein"}:
        same_graph = graph_ids[:, None] == graph_ids[None, :]
        diagonal = torch.eye(logits.size(0), device=logits.device, dtype=torch.bool)
        allowed = (~same_graph) | diagonal
        if args.contrastive_negatives == "other_protein_far_same_protein":
            seq_gap = torch.abs(idx[:, None] - idx[None, :]) > int(args.contrastive_same_protein_seq_gap)
            ca_dist = torch.cdist(apo_pos[idx], apo_pos[idx]) > float(args.contrastive_same_protein_ca_cutoff)
            allowed = allowed | (same_graph & seq_gap & ca_dist)
        logits_ab = logits.masked_fill(~allowed, -1.0e9)
        logits_ba = logits.t().masked_fill(~allowed.t(), -1.0e9)
        neg_per_anchor = (allowed.sum(dim=1).float() - 1.0).mean()
    else:
        logits_ab = logits
        logits_ba = logits.t()
        neg_per_anchor = logits.new_tensor(float(max(0, logits.size(0) - 1)))

    loss_ab = F.cross_entropy(logits_ab, labels)
    loss_ba = F.cross_entropy(logits_ba, labels)
    loss = 0.5 * (loss_ab + loss_ba)
    acc_ab = (logits_ab.argmax(dim=1) == labels).float().mean()
    acc_ba = (logits_ba.argmax(dim=1) == labels).float().mean()
    pos_sim = torch.diagonal(q @ k.t()).mean()
    return loss, {
        "contrastive_count": float(idx.numel()),
        "contrastive_acc": float((0.5 * (acc_ab + acc_ba)).item()),
        "contrastive_pos_sim": float(pos_sim.item()),
        "contrastive_neg_per_anchor": float(neg_per_anchor.item()),
    }


def build_pseudo_pocket_targets(
    apo_pos: Tensor,
    holo_pos: Tensor,
    batch: Tensor,
    neighbor_cutoff: float,
    positive_frac: float,
    negative_frac: float,
    density_weight: float,
) -> Tuple[Tensor, Tensor, Tensor]:
    labels = apo_pos.new_zeros((apo_pos.size(0),))
    mask = torch.zeros((apo_pos.size(0),), device=apo_pos.device, dtype=torch.bool)
    score = apo_pos.new_zeros((apo_pos.size(0),))

    for graph_id in torch.unique(batch):
        idx = torch.nonzero(batch == graph_id, as_tuple=False).view(-1)
        n = int(idx.numel())
        if n < 3:
            continue

        apo = apo_pos[idx]
        holo = holo_pos[idx]
        d_apo = torch.cdist(apo, apo)
        d_holo = torch.cdist(holo, holo)
        not_self = ~torch.eye(n, device=apo_pos.device, dtype=torch.bool)
        neigh_apo = (d_apo < float(neighbor_cutoff)) & not_self
        neigh_holo = (d_holo < float(neighbor_cutoff)) & not_self

        apo_count = neigh_apo.sum(dim=1).clamp(min=1).to(apo_pos.dtype)
        expansion = (d_holo - d_apo).clamp(min=0.0)
        mean_expansion = (expansion * neigh_apo.to(expansion.dtype)).sum(dim=1) / apo_count
        density_drop = (neigh_apo.sum(dim=1) - neigh_holo.sum(dim=1)).clamp(min=0).to(apo_pos.dtype) / apo_count
        graph_score = mean_expansion + float(density_weight) * density_drop
        score[idx] = graph_score

        order = torch.argsort(graph_score, descending=True)
        k_pos = max(1, int(round(n * float(positive_frac))))
        k_neg = max(1, int(round(n * float(negative_frac))))
        k_pos = min(k_pos, n)
        k_neg = min(k_neg, max(0, n - k_pos))
        if k_neg == 0:
            continue

        pos_idx = idx[order[:k_pos]]
        neg_idx = idx[order[-k_neg:]]
        labels[pos_idx] = 1.0
        mask[pos_idx] = True
        mask[neg_idx] = True

    return labels, mask, score


def pseudo_pocket_loss(
    pseudo_logits: Tensor,
    apo_pos: Tensor,
    holo_pos: Tensor,
    batch: Tensor,
    args: argparse.Namespace,
) -> Tuple[Tensor, Dict[str, float]]:
    labels, mask, score = build_pseudo_pocket_targets(
        apo_pos=apo_pos,
        holo_pos=holo_pos,
        batch=batch,
        neighbor_cutoff=args.pseudo_neighbor_cutoff,
        positive_frac=args.pseudo_positive_frac,
        negative_frac=args.pseudo_negative_frac,
        density_weight=args.pseudo_density_weight,
    )
    if not bool(mask.any()):
        return pseudo_logits.new_zeros(()), {
            "pseudo_count": 0.0,
            "pseudo_pos": 0.0,
            "pseudo_acc": float("nan"),
            "pseudo_auc": float("nan"),
            "opening_score": 0.0,
        }

    pos_weight = torch.tensor([args.pseudo_pos_weight], device=pseudo_logits.device, dtype=torch.float32)
    loss = F.binary_cross_entropy_with_logits(
        pseudo_logits[mask],
        labels[mask],
        pos_weight=pos_weight,
    )
    prob = torch.sigmoid(pseudo_logits[mask])
    pred = (prob >= 0.5).to(labels.dtype)
    acc = float((pred == labels[mask]).float().mean().item())
    auc = binary_auc_torch(labels[mask].detach().cpu(), prob.detach().cpu())
    return loss, {
        "pseudo_count": float(mask.sum().item()),
        "pseudo_pos": float(labels[mask].sum().item()),
        "pseudo_acc": acc,
        "pseudo_auc": auc,
        "opening_score": float(score[mask].mean().item()),
    }


def edge_delta_ranking_loss(
    edge_scores: Tensor,
    apo_pos: Tensor,
    holo_pos: Tensor,
    edge_index: Tensor,
    margin_delta: float,
    margin_score: float,
    max_pairs: int,
) -> Tuple[Tensor, int]:
    if edge_scores.numel() < 2 or edge_index.numel() == 0 or max_pairs <= 0:
        return edge_scores.new_zeros(()), 0

    src, dst = edge_index
    apo_dist = (apo_pos[src] - apo_pos[dst]).norm(dim=-1)
    holo_dist = (holo_pos[src] - holo_pos[dst]).norm(dim=-1)
    delta_mag = (holo_dist - apo_dist).abs()

    n_edges = int(edge_scores.numel())
    n_pairs = min(int(max_pairs), n_edges * max(1, n_edges - 1))
    idx_a = torch.randint(n_edges, (n_pairs,), device=edge_scores.device)
    idx_b = torch.randint(n_edges, (n_pairs,), device=edge_scores.device)
    valid = idx_a != idx_b
    idx_a = idx_a[valid]
    idx_b = idx_b[valid]
    if idx_a.numel() == 0:
        return edge_scores.new_zeros(()), 0

    delta_diff = delta_mag[idx_a] - delta_mag[idx_b]
    valid = delta_diff.abs() > float(margin_delta)
    if not bool(valid.any()):
        return edge_scores.new_zeros(()), 0

    idx_a = idx_a[valid]
    idx_b = idx_b[valid]
    delta_diff = delta_diff[valid]
    high_idx = torch.where(delta_diff > 0, idx_a, idx_b)
    low_idx = torch.where(delta_diff > 0, idx_b, idx_a)
    score_gap = edge_scores[high_idx] - edge_scores[low_idx]
    loss = F.relu(float(margin_score) - score_gap).mean()
    return loss, int(score_gap.numel())


def train_one_epoch(
    model: EdgeGCLModel,
    loader: Iterable[Data],
    optimizer: torch.optim.Optimizer,
    scaler: torch.cuda.amp.GradScaler | None,
    device: torch.device,
    args: argparse.Namespace,
) -> Dict[str, float]:
    model.train()

    total = 0
    total_loss = 0.0
    total_contrastive = 0.0
    total_edge = 0.0
    total_ranking = 0.0
    total_pseudo = 0.0
    total_contrastive_acc = 0.0
    total_contrastive_pos_sim = 0.0
    total_contrastive_neg_per_anchor = 0.0
    total_pseudo_acc = 0.0
    total_pseudo_auc = 0.0
    total_opening_score = 0.0
    contrastive_count = 0.0
    edge_count = 0
    ranking_count = 0
    pseudo_count = 0.0
    pseudo_pos = 0.0
    correct = 0

    pos_weight = torch.tensor([args.edge_pos_weight], device=device, dtype=torch.float32)

    for batch in loader:
        batch = safe_to_device(batch, device)
        optimizer.zero_grad(set_to_none=True)

        use_amp = scaler is not None and device.type == "cuda"
        amp_ctx = torch.cuda.amp.autocast(dtype=torch.float16) if use_amp else contextlib.nullcontext()
        with amp_ctx:
            loss_pseudo = batch.apo_pos.new_zeros(())
            pseudo_m = {
                "pseudo_count": 0.0,
                "pseudo_pos": 0.0,
                "pseudo_acc": float("nan"),
                "pseudo_auc": float("nan"),
                "opening_score": 0.0,
            }
            contrastive_m = {
                "contrastive_count": 0.0,
                "contrastive_acc": float("nan"),
                "contrastive_pos_sim": float("nan"),
                "contrastive_neg_per_anchor": 0.0,
            }
            if args.lambda_pseudo > 0:
                pseudo_logits, edge_logits = model.forward_pseudo(
                    apo_pos=batch.apo_pos,
                    sequence=batch.sequence,
                    batch=batch.batch,
                    apo_backbone=getattr(batch, "apo_backbone", None),
                    apo_backbone_mask=getattr(batch, "apo_backbone_mask", None),
                    edge_index=batch.edge_index,
                    compute_edge=(args.lambda_edge > 0 or args.lambda_ranking > 0),
                )
                loss_contrastive = edge_logits.new_zeros(())
                loss_pseudo, pseudo_m = pseudo_pocket_loss(
                    pseudo_logits=pseudo_logits,
                    apo_pos=batch.apo_pos,
                    holo_pos=batch.holo_pos,
                    batch=batch.batch,
                    args=args,
                )
            else:
                if args.lambda_contrastive > 0 and args.contrastive_variant == "sampled_apo_holo":
                    out = model(
                        apo_pos=batch.apo_pos,
                        holo_pos=batch.holo_pos,
                        edge_index=batch.edge_index,
                        sequence=batch.sequence,
                        batch=batch.batch,
                        apo_backbone=getattr(batch, "apo_backbone", None),
                        holo_backbone=getattr(batch, "holo_backbone", None),
                        apo_backbone_mask=getattr(batch, "apo_backbone_mask", None),
                        holo_backbone_mask=getattr(batch, "holo_backbone_mask", None),
                    )
                    loss_contrastive, contrastive_m = sampled_apo_holo_contrastive_loss(
                        model=model,
                        z_apo=out["z_apo"],
                        z_holo=out["z_holo"],
                        apo_pos=batch.apo_pos,
                        holo_pos=batch.holo_pos,
                        batch=batch.batch,
                        args=args,
                    )
                    edge_logits = out["edge_logits"]
                else:
                    loss_contrastive, edge_logits = model.forward_train(
                        apo_pos=batch.apo_pos,
                        holo_pos=batch.holo_pos,
                        edge_index=batch.edge_index,
                        sequence=batch.sequence,
                        batch=batch.batch,
                        apo_backbone=getattr(batch, "apo_backbone", None),
                        holo_backbone=getattr(batch, "holo_backbone", None),
                        apo_backbone_mask=getattr(batch, "apo_backbone_mask", None),
                        holo_backbone_mask=getattr(batch, "holo_backbone_mask", None),
                        compute_contrastive=args.lambda_contrastive > 0,
                    )
            if args.lambda_edge > 0 or args.lambda_ranking > 0:
                loss_edge, this_edge_count = edge_loss_with_empty_support(
                    edge_logits=edge_logits,
                    edge_label=batch.edge_label,
                    pos_weight=pos_weight,
                )
            else:
                loss_edge = batch.apo_pos.new_zeros(())
                this_edge_count = 0
            if args.lambda_ranking > 0:
                loss_ranking, this_ranking_count = edge_delta_ranking_loss(
                    edge_scores=edge_logits,
                    apo_pos=batch.apo_pos,
                    holo_pos=batch.holo_pos,
                    edge_index=batch.edge_index,
                    margin_delta=args.ranking_margin_delta,
                    margin_score=args.ranking_margin_score,
                    max_pairs=args.ranking_max_pairs,
                )
            else:
                loss_ranking = edge_logits.new_zeros(())
                this_ranking_count = 0
            loss = (
                args.lambda_contrastive * loss_contrastive
                + args.lambda_edge * loss_edge
                + args.lambda_ranking * loss_ranking
                + args.lambda_pseudo * loss_pseudo
            )

        if use_amp:
            assert scaler is not None
            scaler.scale(loss).backward()
            if args.grad_clip > 0:
                scaler.unscale_(optimizer)
                torch.nn.utils.clip_grad_norm_(model.parameters(), args.grad_clip)
            scaler.step(optimizer)
            scaler.update()
        else:
            loss.backward()
            if args.grad_clip > 0:
                torch.nn.utils.clip_grad_norm_(model.parameters(), args.grad_clip)
            optimizer.step()

        batch_size_graph = int(batch.num_graphs)
        total += batch_size_graph
        total_loss += float(loss.item()) * batch_size_graph
        total_contrastive += float(loss_contrastive.item()) * batch_size_graph
        total_edge += float(loss_edge.item()) * batch_size_graph
        total_ranking += float(loss_ranking.item()) * batch_size_graph
        total_pseudo += float(loss_pseudo.item()) * batch_size_graph
        contrastive_count += contrastive_m["contrastive_count"]
        if contrastive_m["contrastive_count"] > 0:
            total_contrastive_acc += contrastive_m["contrastive_acc"] * batch_size_graph
            total_contrastive_pos_sim += contrastive_m["contrastive_pos_sim"] * batch_size_graph
            total_contrastive_neg_per_anchor += contrastive_m["contrastive_neg_per_anchor"] * batch_size_graph
        ranking_count += this_ranking_count
        pseudo_count += pseudo_m["pseudo_count"]
        pseudo_pos += pseudo_m["pseudo_pos"]
        if pseudo_m["pseudo_count"] > 0:
            total_pseudo_acc += pseudo_m["pseudo_acc"] * batch_size_graph
            if pseudo_m["pseudo_auc"] == pseudo_m["pseudo_auc"]:
                total_pseudo_auc += pseudo_m["pseudo_auc"] * batch_size_graph
            total_opening_score += pseudo_m["opening_score"] * batch_size_graph

        if this_edge_count > 0:
            preds = (torch.sigmoid(edge_logits) >= 0.5).long()
            correct += int((preds == batch.edge_label.long()).sum().item())
            edge_count += this_edge_count

    metrics = {
        "loss": total_loss / max(1, total),
        "loss_contrastive": total_contrastive / max(1, total),
        "loss_edge": total_edge / max(1, total),
        "loss_ranking": total_ranking / max(1, total),
        "loss_pseudo": total_pseudo / max(1, total),
        "contrastive_count": float(contrastive_count),
        "contrastive_acc": total_contrastive_acc / max(1, total),
        "contrastive_pos_sim": total_contrastive_pos_sim / max(1, total),
        "contrastive_neg_per_anchor": total_contrastive_neg_per_anchor / max(1, total),
        "edge_acc": (correct / edge_count) if edge_count > 0 else float("nan"),
        "edge_count": float(edge_count),
        "ranking_count": float(ranking_count),
        "pseudo_count": float(pseudo_count),
        "pseudo_pos_frac": float(pseudo_pos / max(1.0, pseudo_count)),
        "pseudo_acc": total_pseudo_acc / max(1, total),
        "pseudo_auc": total_pseudo_auc / max(1, total),
        "opening_score": total_opening_score / max(1, total),
    }
    return metrics


