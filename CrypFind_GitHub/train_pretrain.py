def load_checkpoint_if_needed(
    model: EdgeGCLModel,
    optimizer: torch.optim.Optimizer,
    scaler: torch.cuda.amp.GradScaler | None,
    ckpt_path: Path,
    device: torch.device,
) -> Tuple[int, float]:
    ckpt = torch.load(ckpt_path, map_location=device)
    model.load_state_dict(ckpt["model"])
    optimizer.load_state_dict(ckpt["optimizer"])
    if scaler is not None and ckpt.get("scaler") is not None:
        scaler.load_state_dict(ckpt["scaler"])
    start_epoch = int(ckpt.get("epoch", 0)) + 1
    best_val = float(ckpt.get("best_val_loss", float("inf")))
    return start_epoch, best_val


def save_checkpoint(
    path: Path,
    model: EdgeGCLModel,
    optimizer: torch.optim.Optimizer,
    scaler: torch.cuda.amp.GradScaler | None,
    epoch: int,
    best_val_loss: float,
    args: argparse.Namespace,
) -> None:
    state = {
        "epoch": epoch,
        "best_val_loss": best_val_loss,
        "model": model.state_dict(),
        "pockmon_backbone": model.pockmon_backbone_state_dict(),
        "optimizer": optimizer.state_dict(),
        "scaler": scaler.state_dict() if scaler is not None else None,
        "args": vars(args),
    }
    torch.save(state, path)


def main() -> None:
    args = parse_args()
    save_dir = Path(args.save_dir)
    setup_logging(save_dir)
    set_seed(args.seed)

    device = select_device(args.device)
    logging.info("Device: %s", device)

    data_dir = Path(args.data_dir)
    files = list_pt_files(data_dir)
    if args.max_samples > 0:
        files = files[: args.max_samples]
    validate_graph_files(files, args.validate_first_n)
    n_total = len(files)
    if n_total < 2:
        raise ValueError(f"Need at least 2 samples for train/val split, got {n_total}")

    train_idx, val_idx = split_indices(n_total, args.val_ratio, args.seed)
    logging.info("Total samples: %d | train: %d | val: %d", n_total, len(train_idx), len(val_idx))

    dataset = PTGraphDataset(files)
    train_set = Subset(dataset, train_idx)
    val_set = Subset(dataset, val_idx)

    train_loader = DataLoader(
        train_set,
        batch_size=args.batch_size,
        shuffle=True,
        num_workers=args.num_workers,
        pin_memory=(device.type == "cuda"),
    )
    val_loader = DataLoader(
        val_set,
        batch_size=args.batch_size,
        shuffle=False,
        num_workers=args.num_workers,
        pin_memory=(device.type == "cuda"),
    )

    model = build_model_from_args(args).to(device)
    optimizer = AdamW(model.parameters(), lr=args.lr, weight_decay=args.weight_decay)
    scaler_obj = torch.cuda.amp.GradScaler(enabled=True) if (args.amp and device.type == "cuda") else None

    start_epoch = 1
    best_val_loss = float("inf")

    if args.resume:
        resume_path = Path(args.resume)
        if not resume_path.exists():
            raise FileNotFoundError(f"Resume checkpoint not found: {resume_path}")
        start_epoch, best_val_loss = load_checkpoint_if_needed(
            model=model,
            optimizer=optimizer,
            scaler=scaler_obj,
            ckpt_path=resume_path,
            device=device,
        )
        logging.info("Resumed from %s (start epoch %d)", resume_path, start_epoch)

    config_dump = {
        "args": vars(args),
        "device": str(device),
        "train_size": len(train_set),
        "val_size": len(val_set),
    }
    save_json(save_dir / "run_config.json", config_dump)

    history_path = save_dir / "history.jsonl"
    logging.info("Start training for %d epochs", args.epochs)
    train_start = time.time()

    for epoch in range(start_epoch, args.epochs + 1):
        t0 = time.time()
        train_m = train_one_epoch(
            model=model,
            loader=train_loader,
            optimizer=optimizer,
            scaler=scaler_obj,
            device=device,
            args=args,
        )
        val_m = evaluate(model=model, loader=val_loader, device=device, args=args)
        dt = time.time() - t0

        row = {
            "epoch": epoch,
            "seconds": dt,
            "train": train_m,
            "val": val_m,
        }
        with history_path.open("a", encoding="utf-8") as f:
            f.write(json.dumps(row, ensure_ascii=False) + "\n")

        logging.info(
            (
                "Epoch %d | %.1fs | "
                "train loss %.4f (p %.4f, c %.4f, cacc %.4f, csim %.4f, e %.4f, r %.4f, pacc %.4f, p_auc %.4f, eacc %.4f) | "
                "val loss %.4f (p %.4f, c %.4f, cacc %.4f, csim %.4f, e %.4f, r %.4f, pacc %.4f, p_auc %.4f, eacc %.4f, e_auc %.4f)"
            ),
            epoch,
            dt,
            train_m["loss"],
            train_m["loss_pseudo"],
            train_m["loss_contrastive"],
            train_m["contrastive_acc"],
            train_m["contrastive_pos_sim"],
            train_m["loss_edge"],
            train_m["loss_ranking"],
            train_m["pseudo_acc"],
            train_m["pseudo_auc"],
            train_m["edge_acc"],
            val_m["loss"],
            val_m["loss_pseudo"],
            val_m["loss_contrastive"],
            val_m["contrastive_acc"],
            val_m["contrastive_pos_sim"],
            val_m["loss_edge"],
            val_m["loss_ranking"],
            val_m["pseudo_acc"],
            val_m["pseudo_auc"],
            val_m["edge_acc"],
            val_m["edge_auc"],
        )

        if epoch % args.save_every == 0:
            save_checkpoint(
                path=save_dir / f"epoch_{epoch}.pt",
                model=model,
                optimizer=optimizer,
                scaler=scaler_obj,
                epoch=epoch,
                best_val_loss=best_val_loss,
                args=args,
            )

        if val_m["loss"] < best_val_loss:
            best_val_loss = val_m["loss"]
            save_checkpoint(
                path=save_dir / "best.pt",
                model=model,
                optimizer=optimizer,
                scaler=scaler_obj,
                epoch=epoch,
                best_val_loss=best_val_loss,
                args=args,
            )

    total_time = time.time() - train_start
    logging.info("Training completed in %.1f sec (%.2f hours)", total_time, total_time / 3600.0)
    logging.info("Best val loss: %.6f", best_val_loss)


if __name__ == "__main__":
    main()
